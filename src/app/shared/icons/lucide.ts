/** Kebab-case Lucide names that are registered (from the map's values). */
const REGISTERED_LUCIDE_NAMES = new Set<string>(Object.values(MATERIAL_TO_LUCIDE));

/**
 * Resolve any incoming icon name (legacy Material or native Lucide) to a
 * registered Lucide name.
 *
 * Category icons arrive from the backend as arbitrary Material Icons names, so
 * anything not in the map — and not already a known registered Lucide name —
 * resolves to FALLBACK_ICON. This guarantees a glyph always renders (never an
 * empty box) instead of passing an unknown name straight to lucide-angular,
 * which would render nothing.
 */
export function resolveIconName(name: string): string {
  if (!name) return FALLBACK_ICON;
  const mapped = MATERIAL_TO_LUCIDE[name];
  if (mapped) return mapped;
  // Allow native Lucide (kebab-case) names only if they're registered.
  if (REGISTERED_LUCIDE_NAMES.has(name)) return name;
  return FALLBACK_ICON;
}
